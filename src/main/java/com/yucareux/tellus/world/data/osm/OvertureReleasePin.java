package com.yucareux.tellus.world.data.osm;

import com.google.gson.Gson;
import com.google.gson.GsonBuilder;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import com.yucareux.tellus.Tellus;
import com.yucareux.tellus.cache.TellusCacheFiles;
import com.yucareux.tellus.worldgen.TellusWorldgenSources;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.Objects;

/**
 * Keeps each world on the Overture release its chunks were generated from.
 *
 * <p>Overture publishes a new release about monthly and removes old ones after a few months. Reading whichever
 * release is newest at every server start lets the coastlines, rivers and lakes of new chunks differ from the
 * chunks next to them. The world folder therefore records its release, and the world keeps it until Overture no
 * longer publishes it; only then does it move to the newest release, with a warning in the log. The
 * {@code tellus.overture.release} property still overrides the record, and a source whose own
 * {@code tellus.overture.*.pmtiles} property names an archive reads that archive regardless.</p>
 */
public final class OvertureReleasePin {
   static final String RECORD_FILE = "tellus/data-sources.json";
   private static final String RELEASE_FIELD = "overtureRelease";
   private static final long MAX_RECORD_BYTES = 64L * 1024L;
   private static final Gson GSON = new GsonBuilder().setPrettyPrinting().create();
   private static volatile OvertureReleasePin.PendingRecord pendingRecord;

   private OvertureReleasePin() {
   }

   /**
    * Binds the release recorded for the world in {@code worldRoot}, or chooses one if it has none. Runs before the
    * server loads any level, when it is not yet known whether Tellus generates the world, so a new record is
    * written only by {@link #recordForTellusWorld}.
    */
   public static void bindWorld(Path worldRoot) {
      Path recordFile = Objects.requireNonNull(worldRoot, "worldRoot").resolve(RECORD_FILE);
      pendingRecord = null;
      String configured = OvertureTileUrls.configuredRelease();
      if (configured != null) {
         Tellus.LOGGER.debug("Overture tiles release {} set by tellus.overture.release; the world's record is left as it is", configured);
         TellusWorldgenSources.rebindOvertureSources();
         return;
      }

      String recorded = readRecordedRelease(recordFile);
      List<String> published = OvertureTileUrls.listPublishedReleases();
      OvertureReleasePin.Decision decision = decide(recorded, published, OvertureTileUrls.fallbackRelease());
      if (decision.replacedRelease() != null) {
         Tellus.LOGGER.warn(
            "Overture no longer publishes tiles release {}, which this world was generated with; new chunks use {}, so their map features may not line up with older chunks",
            decision.replacedRelease(),
            decision.release()
         );
      } else if (recorded != null) {
         Tellus.LOGGER.info("Using Overture tiles release {} recorded for this world", decision.release());
      }

      if (decision.writeRecord()) {
         pendingRecord = new OvertureReleasePin.PendingRecord(recordFile, decision.release());
      }

      OvertureTileUrls.bindWorldRelease(decision.release());
      TellusWorldgenSources.rebindOvertureSources();
   }

   /** Writes the release {@link #bindWorld} chose into the world folder, once a level of it is generated by Tellus. */
   public static void recordForTellusWorld(Path worldRoot) {
      OvertureReleasePin.PendingRecord pending = pendingRecord;
      if (pending == null || !pending.recordFile().equals(Objects.requireNonNull(worldRoot, "worldRoot").resolve(RECORD_FILE))) {
         return;
      }

      pendingRecord = null;
      Tellus.LOGGER.info("Recording Overture tiles release {} for this world", pending.release());
      writeRecordedRelease(pending.recordFile(), pending.release());
   }

   /**
    * Chooses a world's release. {@code published} is null when the listing could not be read; a recorded release
    * is then kept, since its absence from the listing is unknown. {@code fallback} serves a world without a record
    * when the listing is unavailable.
    */
   static OvertureReleasePin.Decision decide(String recorded, List<String> published, String fallback) {
      boolean listed = published != null && !published.isEmpty();
      if (OvertureTileUrls.isValidRelease(recorded)) {
         if (!listed || published.contains(recorded)) {
            return new OvertureReleasePin.Decision(recorded, false, null);
         }

         return new OvertureReleasePin.Decision(published.get(published.size() - 1), true, recorded);
      }

      return new OvertureReleasePin.Decision(listed ? published.get(published.size() - 1) : fallback, true, null);
   }

   static String readRecordedRelease(Path recordFile) {
      try {
         if (!Files.isRegularFile(recordFile)) {
            return null;
         }
         if (Files.size(recordFile) > MAX_RECORD_BYTES) {
            throw new IOException("Larger than " + MAX_RECORD_BYTES + " bytes");
         }

         JsonElement root = JsonParser.parseString(Files.readString(recordFile, StandardCharsets.UTF_8));
         JsonElement release = root.isJsonObject() ? root.getAsJsonObject().get(RELEASE_FIELD) : null;
         String value = release != null && release.isJsonPrimitive() ? release.getAsString().trim() : null;
         if (value != null && !OvertureTileUrls.isValidRelease(value)) {
            Tellus.LOGGER.warn("Ignoring invalid Overture release '{}' recorded in {}", value, recordFile);
            return null;
         }
         return value;
      } catch (IOException | RuntimeException error) {
         Tellus.LOGGER.warn("Failed to read the data sources recorded in {}; recording them again", recordFile, error);
         return null;
      }
   }

   /** Records {@code release}, keeping any other fields of the file. */
   static void writeRecordedRelease(Path recordFile, String release) {
      JsonObject root = new JsonObject();
      try {
         if (Files.isRegularFile(recordFile) && Files.size(recordFile) <= MAX_RECORD_BYTES) {
            JsonElement existing = JsonParser.parseString(Files.readString(recordFile, StandardCharsets.UTF_8));
            if (existing.isJsonObject()) {
               root = existing.getAsJsonObject();
            }
         }
      } catch (IOException | RuntimeException ignored) {
         // Unreadable: replaced by a fresh record below.
      }

      root.addProperty(RELEASE_FIELD, release);
      try {
         TellusCacheFiles.writeBytes(recordFile, (GSON.toJson(root) + "\n").getBytes(StandardCharsets.UTF_8));
      } catch (IOException | RuntimeException error) {
         Tellus.LOGGER.warn("Failed to record Overture tiles release {} in {}", release, recordFile, error);
      }
   }

   /** The release to bind; {@code replacedRelease} is the recorded one it replaces because it was withdrawn. */
   record Decision(String release, boolean writeRecord, String replacedRelease) {
   }

   private record PendingRecord(Path recordFile, String release) {
   }
}
